import { defineConfig } from 'vite';
import { readFileSync } from 'node:fs';
import { LINKS } from './src/links.js';

// Set SITE_URL at build time (Vercel env var) to the production domain. The default is the Vercel project URL and is a guess.
const SITE = (process.env.SITE_URL || 'https://flowfi2.vercel.app').replace(/\/$/, '');
const today = new Date().toISOString().slice(0, 10);

const robots = `User-agent: *
Allow: /

# Search and answer engines may read and cite this site.
User-agent: GPTBot
User-agent: OAI-SearchBot
User-agent: ChatGPT-User
User-agent: ClaudeBot
User-agent: Claude-SearchBot
User-agent: PerplexityBot
User-agent: Google-Extended
User-agent: Applebot-Extended
Allow: /

Sitemap: ${SITE}/sitemap.xml
`;

const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
  <url><loc>${SITE}/</loc><lastmod>${today}</lastmod></url>
</urlset>
`;

// llms.txt: a plain-text digest for language-model crawlers. Every fact below is on the page and in the whitepaper link.
const llms = `# FlowFi

> Decentralized infrastructure for the institutional management of on-chain capital. FlowFi runs a Governance Treasury and an Investor Treasury, and caps the FF token at 1 Billion.

## Key facts
- Governance Treasury: manages protocol parameters, voting weights and the FF consensus mechanism. 1.2B FF is locked in it.
- Investor Treasury: grows capital through audited deployment and incubation. It holds $10M+ in seed capital.
- FF token: capped at 1 Billion. No inflation, no minting.
- Black Hole Launch: FlowFi's fair launch distribution. 100% transparent, no VC pre-allocations, 50% to ecosystem incentives and builder grants.
- Deep collateral: an over-collateralized ratio keeps the protocol solvent and stable.
- Audit and partners: Certik audited. Bitget Wallet partner.
- Roadmap: Phase 01 System Launch (Genesis Governance, active), Phase 02 Expansion (Backflow Optimization, in progress), Phase 03 Global Tier (Enterprise Scaling, planned). The goal is moving capital to the ENI Mainnet.

## Links
- [FlowFi home page](${SITE}/): overview, architecture, economics, roadmap and FAQ.
- [FlowFi whitepaper](${LINKS.whitepaper}): full documentation.
`;

function flowfiSeo() {
    return {
        name: 'flowfi-seo',
        transformIndexHtml: (html) => html
            // <!--svg:name--> inlines scripts/snippets/name.svg (generated by scripts/make-home-assets.py); GSAP animates their paths, so they cannot be <img>.
            .replace(/<!--svg:([\w-]+)-->/g, (_, name) => readFileSync(new URL(`./scripts/snippets/${name}.svg`, import.meta.url), 'utf8').trim())
            .replaceAll('__SITE_URL__', SITE)
            .replace(/\{\{link:(\w+)\}\}/g, (_, key) => LINKS[key] || '#'),
        generateBundle() {
            this.emitFile({ type: 'asset', fileName: 'robots.txt', source: robots });
            this.emitFile({ type: 'asset', fileName: 'sitemap.xml', source: sitemap });
            this.emitFile({ type: 'asset', fileName: 'llms.txt', source: llms });
        }
    };
}

// allowedHosts: lets a Cloudflare quick tunnel (cloudflared tunnel --url http://localhost:5174) reach the dev server for previews
export default defineConfig({ plugins: [flowfiSeo()], server: { allowedHosts: ['.trycloudflare.com'] } });
