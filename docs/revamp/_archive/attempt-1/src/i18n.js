export function setupI18n() {
    let currentLang = localStorage.getItem('flowfi_lang') || 'en';

    const updateContent = (lang) => {
        const elements = document.querySelectorAll('[data-i18n]');
        elements.forEach(el => {
            const key = el.getAttribute('data-i18n');
            if (translations[lang] && translations[lang][key]) {
                if (el.tagName === 'INPUT' && el.getAttribute('placeholder')) {
                    el.setAttribute('placeholder', translations[lang][key]);
                } else {
                    el.innerHTML = translations[lang][key];
                }
            }
        });

        // Also update any double-text roll-up buttons that have data-i18n on their wrapper or spans
        const rollUpTextElements = document.querySelectorAll('[data-i18n-rollup]');
        rollUpTextElements.forEach(el => {
            const key = el.getAttribute('data-i18n-rollup');
            if (translations[lang] && translations[lang][key]) {
                const text = translations[lang][key];
                const spans = el.querySelectorAll('span');
                spans.forEach(s => {
                    s.textContent = text;
                });
            }
        });

        const switcherLabel = document.getElementById('lang-switcher-label');
        if (switcherLabel) {
            switcherLabel.innerText = lang.toUpperCase();
        }
    };

    window.setLanguage = (lang) => {
        currentLang = lang;
        localStorage.setItem('flowfi_lang', lang);
        updateContent(lang);
    };

    updateContent(currentLang);
}
